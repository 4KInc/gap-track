#!/usr/bin/env node
/**
 * Attach a published description track to the app's catalogue.
 *
 *   npx tsx scripts/attach-track.ts \
 *     --title bbb \
 *     --track build/tracks/bbb/track.json \
 *     --video-url https://…/video/index.m3u8 \
 *     --track-url https://…/description/index.m3u8
 *
 * Writes a generated module rather than editing catalogue.ts, because
 * rewriting hand-authored source from a script is how comments and intent
 * get quietly deleted. The catalogue imports this and merges it in.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';

const OUT = 'src/app/tracks.generated.ts';

interface Args {
  title?: string;
  track?: string;
  videoUrl?: string;
  trackUrl?: string;
  previewBase?: string;
}

function parse(argv: string[]): Args {
  const a: Args = {};
  for (let i = 0; i < argv.length; i++) {
    const next = () => argv[++i];
    if (argv[i] === '--title') a.title = next();
    else if (argv[i] === '--track') a.track = next();
    else if (argv[i] === '--video-url') a.videoUrl = next();
    else if (argv[i] === '--track-url') a.trackUrl = next();
    else if (argv[i] === '--preview-base') a.previewBase = next();
  }
  return a;
}

async function main(): Promise<void> {
  const args = parse(process.argv.slice(2));
  const missing = (['title', 'track', 'videoUrl', 'trackUrl'] as const).filter((k) => !args[k]);
  if (missing.length) {
    process.stderr.write(`missing: ${missing.map((m) => `--${m}`).join(', ')}\n`);
    process.exit(2);
  }

  const built = JSON.parse(await readFile(args.track as string, 'utf8'));

  // The preview index is fetched at build time rather than by the app, so a
  // device that cannot decode also does not have to discover what exists.
  let preview: unknown = undefined;
  if (args.previewBase) {
    const base = args.previewBase.endsWith('/') ? args.previewBase : `${args.previewBase}/`;
    const res = await fetch(`${base}frames.json`);
    if (!res.ok) throw new Error(`preview index not reachable: ${res.status}`);
    const idx = (await res.json()) as { fps: number; count: number; frames: string[] };
    preview = { baseUrl: base, fps: idx.fps, count: idx.count, frames: idx.frames };
  }

  // Only the admitted cues travel to the device. Refused ones stay in the
  // build manifest as evidence; shipping them would invite the app to try
  // playing audio that was deliberately never written to the track.
  const manifest = {
    titleId: built.titleId,
    durationMs: built.durationMs,
    cues: built.cues,
  };

  // Just the date and the fact it was generated. The cue and refusal counts
  // were here too, which is true and is the kind of thing this project likes
  // to say — but a library row is not where a viewer wants build statistics.
  // The counts remain in track.json and in the admission overlay, where they
  // are attached to the decisions they describe.
  const provenance = `Generated ${new Date().toISOString().slice(0, 10)}`;

  const body = `/**
 * GENERATED by scripts/attach-track.ts — do not edit.
 *
 * Published description tracks, keyed by title id. Regenerate by rerunning
 * the pipeline with --publish and then attach-track.
 */

import type { CueManifest } from '../player/DescriptionPlayer';

export interface AttachedTrack {
  videoUrl: string;
  trackUrl: string;
  manifest: CueManifest;
  provenance: string;
  /** Stills for devices that cannot decode video. Absent on hardware. */
  preview?: { baseUrl: string; fps: number; count: number; frames: string[] };
}

export const ATTACHED: Record<string, AttachedTrack> = ${JSON.stringify(
    {
      [args.title as string]: {
        videoUrl: args.videoUrl,
        trackUrl: args.trackUrl,
        manifest,
        provenance,
        preview,
      },
    },
    null,
    2,
  )};
`;

  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, body, 'utf8');
  process.stdout.write(`${OUT}\n  ${args.title}: ${manifest.cues.length} cues\n`);
}

main().catch((e) => {
  process.stderr.write(`failed: ${e?.message ?? String(e)}\n`);
  process.exit(1);
});
